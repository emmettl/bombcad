"""Tabulate Moore's nonlinear glass plate curves for BlastCore (Sources/BlastCore/MooreGlassCurves.swift).

    python3 Scripts/moore-glass/tabulate.py <DPlot directory> Sources/BlastCore/MooreGlassCurves.swift

Reads UFC 3-340-02's figures 6-52 (nondimensional load against the centre's and the corners'
largest principal stress) and 6-53 (against the centre's deflection over the thickness), the
DPlot data published with Change 2 (`ufc_3_340_02_dplot_v2.zip` on WBDG, files 06_052.grf and
06_053.grf), each curve 256 points. Each is resampled at 24 points evenly spaced in the log of
the load, which reproduces every one of the 256 within 0.2% on log-log interpolation.
"""

import math
import sys
from pathlib import Path

POINTS = 24


def read(path):
    """DPlot v1.6: the number of curves, then each curve's point count, its points, a symbol line,
    its label and a blank line."""
    lines = [line.strip() for line in open(path, errors="replace")]
    count, i, curves = int(lines[2]), 3, []
    for _ in range(count):
        n = int(lines[i])
        points = [tuple(map(float, lines[i + 1 + j].split(","))) for j in range(n)]
        i += 1 + n + 1
        curves.append((lines[i], points))
        i += 2
    return curves


def loglog(points, x):
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x0 <= x <= x1:
            f = (math.log(x) - math.log(x0)) / (math.log(x1) - math.log(x0))
            return math.exp(math.log(y0) + f * (math.log(y1) - math.log(y0)))
    raise ValueError(x)


def resample(points):
    low, high = math.log(points[0][0]), math.log(points[-1][0])
    xs = [math.exp(low + (high - low) * i / (POINTS - 1)) for i in range(POINTS)]
    xs[0], xs[-1] = points[0][0], points[-1][0]
    table = [(x, loglog(points, x)) for x in xs]
    worst = max(abs(loglog(table, x) / y - 1) for x, y in points)
    assert worst < 0.002, worst
    return table


def swift(points):
    return "[" + ", ".join("SIMD2(%.5g, %.5g)" % p for p in points) + "]"


def main():
    plots, out = Path(sys.argv[1]), Path(sys.argv[2])
    stress, deflection = {}, {}
    for label, points in read(plots / "06_052.grf"):
        ratio = float(label.split(",")[0].split("=")[1])
        stress.setdefault(ratio, {})["centre" if "Center" in label else "corner"] = resample(points)
    for label, points in read(plots / "06_053.grf"):
        deflection[float(label.split("=")[1])] = resample(points)
    rows = []
    for ratio in sorted(deflection):
        rows.append(
            "        MooreGlassCurves.Curves(\n"
            f"            aspect: {ratio:g},\n"
            f"            deflection: {swift(deflection[ratio])},\n"
            f"            centreStress: {swift(stress[ratio]['centre'])},\n"
            f"            cornerStress: {swift(stress[ratio]['corner'])}),"
        )
    out.write_text(
        "// Generated by Scripts/moore-glass/tabulate.py from UFC 3-340-02's figure data; do not edit.\n\n"
        "extension MooreGlassCurves {\n"
        "    /// Figures 6-52 and 6-53 by aspect ratio a/b, each curve (nondimensional load L, value),\n"
        "    /// L = q b⁴ / (E′ t⁴), deflection as X / t and stress as σ b² / (E′ t²), E′ = E / 12(1 − ν²).\n"
        "    static let curves: [Curves] = [\n" + "\n".join(rows) + "\n    ]\n}\n"
    )


if __name__ == "__main__":
    main()
